function parseLocalDate(value: string): Date | null {
  const match = value.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) {
    return null;
  }

  const date = new Date(Number(match[1]), Number(match[2]) - 1, Number(match[3]));
  return Number.isNaN(date.getTime()) ? null : date;
}

function getDurationFromRange(start: unknown, end: unknown): number | undefined {
  const normalizedStart = normalizeOptionalTime(start);
  const normalizedEnd = normalizeOptionalTime(end);
  if (!normalizedStart || !normalizedEnd) {
    return undefined;
  }

  const startMinutes = timeToMinutes(normalizedStart);
  let endMinutes = timeToMinutes(normalizedEnd);
  if (endMinutes <= startMinutes) {
    endMinutes += DAY_MINUTES;
  }
  const duration = endMinutes - startMinutes;
  return duration > 0 ? duration : undefined;
}

function compareScheduleEvents(
  left: ScheduleEvent,
  right: ScheduleEvent,
  payload?: SchedulePayload
): number {
  const leftInterval = getEventInterval(left, payload);
  const rightInterval = getEventInterval(right, payload);
  if (leftInterval.start !== rightInterval.start) {
    return leftInterval.start - rightInterval.start;
  }
  return left.title.localeCompare(right.title, "ru-RU");
}

function getDateDayIndex(date: string): number {
  const match = date.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!match) {
    return getDateDayIndex(todayLocalDate());
  }
  return Math.floor(
    Date.UTC(Number(match[1]), Number(match[2]) - 1, Number(match[3])) / 86400000
  );
}

function dayIndexToDate(dayIndex: number): string {
  const date = new Date(dayIndex * 86400000);
  const year = date.getUTCFullYear();
  const month = `${date.getUTCMonth() + 1}`.padStart(2, "0");
  const day = `${date.getUTCDate()}`.padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function dateTimeToAbsoluteMinute(date: string, time: string): number {
  return getDateDayIndex(normalizeScheduleDate(date)) * DAY_MINUTES + timeToMinutes(time);
}

function absoluteMinuteToDateTime(minutes: number): { date: string; time: string } {
  const rounded = Math.round(minutes);
  const dayIndex = Math.floor(rounded / DAY_MINUTES);
  return {
    date: dayIndexToDate(dayIndex),
    time: minutesToTime(rounded),
  };
}

function getWakeIntervalForDate(
  payload: SchedulePayload,
  date: string
): { start: number; end: number } {
  const settings = normalizeScheduleSettings(payload.settings);
  let dayStart = timeToMinutes(settings.defaultDayStart ?? DEFAULT_DAY_START);
  let dayEnd = timeToMinutes(settings.defaultDayEnd ?? DEFAULT_DAY_END);

  if (settings.energyMode === "low" || settings.dayMode === "recovery") {
    dayStart += 60;
    dayEnd -= 30;
  }
  if (settings.dayMode === "shifted") {
    dayStart += 90;
    dayEnd += 60;
  }

  dayStart = Math.max(0, dayStart);
  while (dayEnd <= dayStart) {
    dayEnd += DAY_MINUTES;
  }

  const base = getDateDayIndex(normalizeScheduleDate(date, payload.selectedDate)) * DAY_MINUTES;
  return {
    start: base + dayStart,
    end: base + dayEnd,
  };
}

function getEventInterval(
  event: ScheduleEvent,
  payload?: SchedulePayload
): { start: number; end: number } {
  const date = normalizeScheduleDate(event.date);
  const start = event.start ?? DEFAULT_DAY_START;
  const startAbs = dateTimeToAbsoluteMinute(date, start);

  if (event.endMode === "until-morning") {
    const nextDate = addScheduleDays(date, 1);
    const endAbs = payload
      ? getWakeIntervalForDate(payload, nextDate).start
      : dateTimeToAbsoluteMinute(nextDate, DEFAULT_DAY_START);
    return {
      start: startAbs,
      end: Math.max(startAbs + MIN_EVENT_DURATION, endAbs),
    };
  }

  if (event.end) {
    const endDate =
      event.endDate ??
      (timeToMinutes(event.end) <= timeToMinutes(start) ? addScheduleDays(date, 1) : date);
    let endAbs = dateTimeToAbsoluteMinute(endDate, event.end);
    if (endAbs <= startAbs) {
      endAbs = startAbs + getEventDurationMinutes(event);
    }
    return { start: startAbs, end: endAbs };
  }

  return { start: startAbs, end: startAbs + getEventDurationMinutes(event) };
}

function rangesOverlapInterval(
  left: { start: number; end: number },
  right: { start: number; end: number }
): boolean {
  return rangesOverlap(left.start, left.end, right.start, right.end);
}

function sumIntervalOverlaps(
  interval: { start: number; end: number },
  ranges: Array<{ start: number; end: number }>
): number {
  return ranges.reduce((total, range) => {
    const start = Math.max(interval.start, range.start);
    const end = Math.min(interval.end, range.end);
    return total + Math.max(0, end - start);
  }, 0);
}

function freeWindowFromAbsoluteRange(start: number, end: number): FreeWindow {
  const startPoint = absoluteMinuteToDateTime(start);
  const endPoint = absoluteMinuteToDateTime(end);
  return {
    date: startPoint.date,
    endDate: endPoint.date !== startPoint.date ? endPoint.date : undefined,
    start,
    end,
  };
}

function buildFreeWindowsForDate(payload: SchedulePayload, date: string): FreeWindow[] {
  const normalizedPayload = normalizeSchedulePayload(payload);
  const dayInterval = getWakeIntervalForDate(normalizedPayload, date);
  const settings = normalizeScheduleSettings(normalizedPayload.settings);
  const buffer = settings.preserveFreeTime ? settings.bufferMinutes ?? DEFAULT_BUFFER_MINUTES : 0;
  const busy = getScheduleEventsForDateRange(normalizedPayload, date, date)
    .filter((event) => {
      if (event.status === "skipped") {
        return false;
      }
      return rangesOverlapInterval(getEventInterval(event, normalizedPayload), dayInterval);
    })
    .map((event) => {
      const interval = getEventInterval(event, normalizedPayload);
      const eventBuffer =
        event.type === "fixed" || event.type === "spontaneous" ? 0 : buffer;
      return {
        start: Math.max(dayInterval.start, interval.start - eventBuffer),
        end: Math.min(dayInterval.end, interval.end + eventBuffer),
      };
    })
    .filter((range) => range.end > range.start)
    .sort((left, right) => left.start - right.start);

  const windows: FreeWindow[] = [];
  let cursor = dayInterval.start;
  for (const range of busy) {
    if (range.start > cursor) {
      windows.push(freeWindowFromAbsoluteRange(cursor, range.start));
    }
    cursor = Math.max(cursor, range.end);
  }

  if (cursor < dayInterval.end) {
    windows.push(freeWindowFromAbsoluteRange(cursor, dayInterval.end));
  }

  return windows.filter((window) => window.end - window.start >= MIN_EVENT_DURATION);
}

