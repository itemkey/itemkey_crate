export function formatScheduleMinutes(minutes: number): string {
  const normalized = Math.max(0, Math.round(minutes));
  const hours = Math.floor(normalized / 60);
  const rest = normalized % 60;
  if (hours === 0) {
    return `${rest}м`;
  }
  if (rest === 0) {
    return `${hours}ч`;
  }
  return `${hours}ч ${rest}м`;
}

export function formatScheduleDateShort(date: string): string {
  const parsed = parseLocalDate(date);
  if (!parsed) {
    return date;
  }

  return new Intl.DateTimeFormat("ru-RU", {
    day: "2-digit",
    month: "2-digit",
    weekday: "short",
  }).format(parsed);
}

export function formatScheduleTimeRange(
  event: ScheduleEvent,
  payload?: SchedulePayload
): string {
  if (event.endMode === "until-morning" && event.start) {
    return `${event.start}-до утра`;
  }
  if (event.start && event.end) {
    return `${event.start}-${event.end}`;
  }
  if (event.start) {
    return `${event.start} · ${formatScheduleMinutes(getEventDurationMinutes(event, payload))}`;
  }
  return formatScheduleMinutes(getEventDurationMinutes(event, payload));
}

export function getEventDurationMinutes(
  event: ScheduleEvent,
  payload?: SchedulePayload
): number {
  if (event.endMode === "until-morning") {
    const interval = getEventInterval(event, payload);
    return Math.max(MIN_EVENT_DURATION, interval.end - interval.start);
  }
  return normalizeScheduleDuration(
    event.durationMinutes,
    getDurationFromRange(event.start, event.end) ?? 60
  );
}

export function timeToMinutes(time: string): number {
  const normalized = normalizeOptionalTime(time) ?? time;
  const [hours, minutes] = normalized.split(":").map((part) => Number(part));
  if (!Number.isFinite(hours) || !Number.isFinite(minutes)) {
    return 0;
  }
  return Math.min(DAY_MINUTES, Math.max(0, hours * 60 + minutes));
}

export function minutesToTime(minutes: number): string {
  const rounded = Math.round(minutes);
  const wrapped = ((rounded % DAY_MINUTES) + DAY_MINUTES) % DAY_MINUTES;
  const hours = Math.floor(wrapped / 60);
  const rest = wrapped % 60;
  return `${`${hours}`.padStart(2, "0")}:${`${rest}`.padStart(2, "0")}`;
}

