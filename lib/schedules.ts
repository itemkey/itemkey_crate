export function todayLocalDate(): string {
  return toLocalDateString(new Date());
}

export function toLocalDateString(date: Date): string {
  const year = date.getFullYear();
  const month = `${date.getMonth() + 1}`.padStart(2, "0");
  const day = `${date.getDate()}`.padStart(2, "0");
  return `${year}-${month}-${day}`;
}

export function addScheduleDays(date: string, days: number): string {
  const base = parseLocalDate(date) ?? parseLocalDate(todayLocalDate()) ?? new Date();
  base.setDate(base.getDate() + days);
  return toLocalDateString(base);
}

export function getScheduleWeekDates(date: string): string[] {
  const base = parseLocalDate(normalizeScheduleDate(date));
  if (!base) {
    return [];
  }

  const day = base.getDay();
  const mondayOffset = day === 0 ? -6 : 1 - day;
  base.setDate(base.getDate() + mondayOffset);

  return Array.from({ length: 7 }, (_, index) => {
    const next = new Date(base);
    next.setDate(base.getDate() + index);
    return toLocalDateString(next);
  });
}

function getScheduleWeekday(date: string): ScheduleWeekday {
  const parsed = parseLocalDate(normalizeScheduleDate(date));
  const day = parsed?.getDay() ?? 1;
  return (day === 0 ? 7 : day) as ScheduleWeekday;
}

export function getDateRange(startDate: string, endDate: string): string[] {
  const start = normalizeScheduleDate(startDate);
  const end = normalizeScheduleDate(endDate, start);
  const dates: string[] = [];
  let cursor = start;

  for (let index = 0; index < 60; index += 1) {
    dates.push(cursor);
    if (cursor >= end) {
      break;
    }
    cursor = addScheduleDays(cursor, 1);
  }

  return dates;
}

