function createAutoTasksFromTemplate(
  task: ScheduleTaskTemplate,
  startDate: string,
  horizonDays: number
): ScheduleAutoTask[] {
  const baseMinutes =
    task.goalMinutes ??
    task.durationMinutes ??
    (task.minDurationMinutes && task.maxDurationMinutes
      ? Math.round((task.minDurationMinutes + task.maxDurationMinutes) / 2)
      : undefined) ??
    (task.goalCount ? task.goalCount * 60 : 60);
  const periodMultiplier =
    task.goalPeriod === "day" ? horizonDays : Math.max(1, Math.ceil(horizonDays / 7));
  const totalMinutes = Math.max(
    MIN_EVENT_DURATION,
    Math.min(
      MAX_EVENT_DURATION * periodMultiplier,
      task.goalPeriod === "day" ? baseMinutes : baseMinutes * periodMultiplier
    )
  );
  const chunkDurations = getTemplateChunkDurations(
    task,
    totalMinutes,
    task.goalPeriod === "day" ? 1 : periodMultiplier
  );
  const frequency: ScheduleAutoTaskFrequency = task.goalPeriod === "day" ? "daily" : "once";

  return chunkDurations.map((durationMinutes, index) =>
    normalizeScheduleAutoTask({
      id: `${task.id}-autoplan-${index + 1}`,
      title:
        chunkDurations.length > 1
          ? `${task.title} ${index + 1}/${chunkDurations.length}`
          : task.title,
      description: task.details || task.description,
      category: task.category,
      priority: task.priority,
      durationMinutes,
      frequency,
      start: task.preferredTimeOfDay,
      type: task.type ?? "flexible",
      canMove: task.type !== "fixed",
      canSplit: false,
      sourceRoutineId: task.id,
    })
  );
}

function getTemplateChunkDurations(
  task: ScheduleTaskTemplate,
  totalMinutes: number,
  periodMultiplier: number
): number[] {
  if (task.canSplit === false) {
    return [totalMinutes];
  }

  const baseCount = task.goalCount
    ? Math.max(1, task.goalCount * periodMultiplier)
    : undefined;
  const defaults = getDefaultRoutineChunkRange(totalMinutes);
  const minChunk = Math.max(
    MIN_EVENT_DURATION,
    Math.min(
      totalMinutes,
      task.minDurationMinutes ?? defaults.minChunkMinutes
    )
  );
  const maxChunk = Math.max(
    minChunk,
    Math.min(
      totalMinutes,
      task.maxDurationMinutes ?? defaults.maxChunkMinutes
    )
  );
  const chunkCount =
    baseCount ??
    (totalMinutes <= 90
      ? 1
      : Math.max(1, Math.ceil(totalMinutes / maxChunk)));
  const durations: number[] = [];
  let remaining = totalMinutes;

  for (let index = 0; index < chunkCount; index += 1) {
    const slotsLeft = chunkCount - index;
    const duration =
      slotsLeft === 1
        ? remaining
        : Math.max(minChunk, Math.min(maxChunk, Math.round(remaining / slotsLeft)));
    durations.push(duration);
    remaining -= duration;
  }

  if (remaining > 0) {
    durations[durations.length - 1] += remaining;
  }

  return durations.filter((duration) => duration >= MIN_EVENT_DURATION);
}

function getDefaultRoutineChunkRange(totalMinutes: number): {
  minChunkMinutes: number;
  maxChunkMinutes: number;
} {
  if (totalMinutes <= 90) {
    return { minChunkMinutes: totalMinutes, maxChunkMinutes: totalMinutes };
  }
  if (totalMinutes <= 240) {
    return { minChunkMinutes: 60, maxChunkMinutes: 90 };
  }
  return { minChunkMinutes: 90, maxChunkMinutes: 120 };
}

function getTaskTargetMinutesForHorizon(
  task: ScheduleTaskTemplate,
  horizonDays: number
): number {
  const baseMinutes =
    task.goalMinutes ??
    task.durationMinutes ??
    (task.goalCount ? task.goalCount * 60 : 0);
  if (baseMinutes <= 0) {
    return 0;
  }
  return task.goalPeriod === "day"
    ? baseMinutes * horizonDays
    : baseMinutes * Math.max(1, Math.ceil(horizonDays / 7));
}

function buildTaskCoverage(
  taskBase: ScheduleTaskTemplate[],
  changes: SchedulePreviewChange[],
  horizonDays: number
): ScheduleAutoplanTaskCoverage[] {
  return taskBase.map((task) => {
    const addedEvents = changes
      .filter((change): change is Extract<SchedulePreviewChange, { kind: "add" }> =>
        change.kind === "add"
      )
      .map((change) => change.event)
      .filter((event) => event.taskId === task.id || event.generatedFromTaskId === task.id);
    const plannedMinutes = addedEvents.reduce(
      (sum, event) => sum + getEventDurationMinutes(event),
      0
    );

    return {
      taskId: task.id,
      title: task.title,
      targetMinutes: getTaskTargetMinutesForHorizon(task, horizonDays),
      plannedMinutes,
      plannedCount: addedEvents.length,
    };
  });
}

function expandAutoTaskInstances(
  tasks: ScheduleAutoTask[],
  startDate: string,
  horizonDays: number
): Array<{ task: ScheduleAutoTask; date: string; index: number }> {
  const instances: Array<{ task: ScheduleAutoTask; date: string; index: number }> = [];
  tasks.forEach((task, taskIndex) => {
    if (task.date) {
      instances.push({ task, date: task.date, index: taskIndex });
      return;
    }

    if (task.frequency === "daily") {
      for (let index = 0; index < horizonDays; index += 1) {
        instances.push({ task, date: addScheduleDays(startDate, index), index: taskIndex });
      }
      return;
    }

    if (task.frequency === "some-days") {
      for (let index = 0; index < horizonDays; index += 2) {
        instances.push({ task, date: addScheduleDays(startDate, index), index: taskIndex });
      }
      return;
    }

    instances.push({ task, date: startDate, index: taskIndex });
  });
  return instances;
}

function compareAutoTaskInstances(
  left: { task: ScheduleAutoTask; date: string; index: number },
  right: { task: ScheduleAutoTask; date: string; index: number }
): number {
  const priorityDiff =
    schedulePriorityWeight(right.task.priority) - schedulePriorityWeight(left.task.priority);
  if (priorityDiff !== 0) {
    return priorityDiff;
  }
  if (left.date !== right.date) {
    return left.date.localeCompare(right.date);
  }
  return left.index - right.index;
}

function schedulePriorityWeight(priority: SchedulePriority | undefined): number {
  if (priority === "critical") {
    return 4;
  }
  if (priority === "high") {
    return 3;
  }
  if (priority === "medium" || !priority) {
    return 2;
  }
  return 1;
}

function createEventFromAutoTask(
  task: ScheduleAutoTask,
  date: string,
  overrides: Partial<ScheduleEvent> = {}
): ScheduleEvent {
  const start = overrides.start ?? task.start;
  const durationMinutes = normalizeScheduleDuration(
    overrides.durationMinutes ?? task.durationMinutes,
    getDurationFromRange(start, overrides.end ?? task.end) ?? 60
  );
  const startDate = normalizeScheduleDate(overrides.date ?? task.date ?? date);
  const startTime = start ?? DEFAULT_DAY_START;
  const startAbs = dateTimeToAbsoluteMinute(startDate, startTime);
  const endPoint = absoluteMinuteToDateTime(startAbs + durationMinutes);

  return normalizeScheduleEvent({
    id: overrides.id ?? createScheduleId("event"),
    taskId: overrides.taskId ?? task.sourceRoutineId,
    title: overrides.title ?? task.title,
    description: overrides.description ?? task.description,
    date: startDate,
    start: startTime,
    end: overrides.end ?? endPoint.time,
    endDate: overrides.endDate ?? (endPoint.date !== startDate ? endPoint.date : undefined),
    durationMinutes,
    type: overrides.type ?? task.type ?? "flexible",
    category: overrides.category ?? task.category,
    priority: overrides.priority ?? task.priority ?? "medium",
    status: overrides.status ?? "planned",
    canMove: overrides.canMove ?? task.canMove ?? true,
    canSplit: overrides.canSplit ?? task.canSplit ?? false,
    deadline: overrides.deadline ?? task.deadline,
    generatedFromTaskId: task.sourceRoutineId ?? task.id,
    generatedFromRoutineId: task.sourceRoutineId,
    autoGenerated: true,
  });
}

function placeAutoTaskInstance(
  payload: SchedulePayload,
  task: ScheduleAutoTask,
  startDate: string,
  horizonEndDate: string
): ScheduleEvent[] {
  const durationMinutes = normalizeScheduleDuration(task.durationMinutes, 60);
  const endDate = task.deadline && task.deadline < horizonEndDate ? task.deadline : horizonEndDate;
  const suggestions = buildScheduleSuggestions(
    payload,
    {
      title: task.title,
      description: task.description,
      durationMinutes,
      dateRangeStart: startDate,
      dateRangeEnd: endDate,
      preferredTime: task.start,
      deadline: task.deadline,
      priority: task.priority,
      category: task.category,
      canMove: true,
      canSplit: task.canSplit,
      type: task.type ?? "flexible",
    },
    startDate
  );

  if (suggestions[0]) {
    return [
      normalizeScheduleEvent({
        ...suggestions[0].event,
        taskId: task.sourceRoutineId,
        generatedFromTaskId: task.sourceRoutineId ?? task.id,
        generatedFromRoutineId: task.sourceRoutineId,
        autoGenerated: true,
      }),
    ];
  }

  if (!task.canSplit || durationMinutes < MIN_SPLIT_CHUNK_MINUTES * 2) {
    return [];
  }

  const placed: ScheduleEvent[] = [];
  let remaining = durationMinutes;
  let workingPayload = payload;
  while (remaining >= MIN_SPLIT_CHUNK_MINUTES) {
    const chunkDuration = Math.min(
      remaining,
      Math.max(MIN_SPLIT_CHUNK_MINUTES, Math.ceil(durationMinutes / 2))
    );
    const chunkSuggestions = buildScheduleSuggestions(
      workingPayload,
      {
        title: task.title,
        description: task.description,
        durationMinutes: chunkDuration,
        dateRangeStart: startDate,
        dateRangeEnd: endDate,
        preferredTime: task.start,
        deadline: task.deadline,
        priority: task.priority,
        category: task.category,
        canMove: true,
        canSplit: false,
        type: task.type ?? "flexible",
      },
      startDate
    );
    const suggestion = chunkSuggestions[0];
    if (!suggestion) {
      break;
    }
    const event = normalizeScheduleEvent({
      ...suggestion.event,
      title: `${task.title} (${placed.length + 1})`,
      taskId: task.sourceRoutineId,
      generatedFromTaskId: task.sourceRoutineId ?? task.id,
      generatedFromRoutineId: task.sourceRoutineId,
      autoGenerated: true,
    });
    placed.push(event);
    workingPayload = {
      ...workingPayload,
      events: normalizeScheduleEvents([...workingPayload.events, event]),
    };
    remaining -= chunkDuration;
  }

  return remaining <= 0 ? placed : [];
}

function isAutoGeneratedEventInDateRange(
  event: ScheduleEvent,
  startDate: string,
  endDate: string
): boolean {
  if (!event.autoGenerated) {
    return false;
  }
  const startAbs = getDateDayIndex(startDate) * DAY_MINUTES;
  const endAbs = (getDateDayIndex(endDate) + 1) * DAY_MINUTES;
  const eventInterval = getEventInterval(event);
  return eventInterval.end > startAbs && eventInterval.start < endAbs;
}

function normalizeAssistantTitle(value: string): string {
  const cleaned = value
    .replace(/мне нужно/gi, "")
    .replace(/надо/gi, "")
    .replace(/примерно/gi, "")
    .replace(
      /\d+(?:[,.]\d+)?\s*(?:часов|часа|час|ч|минут|минуты|мин|м|hours?|minutes?|m|h)(?=$|\s|[.,;:!?])/gi,
      ""
    )
    .replace(/\s+/g, " ")
    .trim();
  return normalizeScheduleEventTitle(cleaned || value || "Новое дело");
}

function buildSuggestionReason(options: {
  preferred: boolean;
  lowLoad: boolean;
  deadline: boolean;
}): string {
  const reasons: string[] = [];
  if (options.preferred) {
    reasons.push("попадает в предпочтительное время");
  }
  if (options.lowLoad) {
    reasons.push("день не перегружен");
  }
  if (options.deadline) {
    reasons.push("успевает до дедлайна");
  }
  return reasons.length > 0 ? reasons.join(", ") : "свободное окно без пересечений";
}

function normalizeComparable(value: string): string {
  return value.trim().toLocaleLowerCase();
}

function normalizeGoalCategoryKey(goal: ScheduleGoal): string {
  return normalizeComparable(goal.category || goal.title);
}
