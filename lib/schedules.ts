export function normalizeScheduleRoutines(value: unknown): ScheduleRoutine[] {
  if (!Array.isArray(value)) {
    return [];
  }

  const seen = new Set<string>();
  const routines: ScheduleRoutine[] = [];
  value.forEach((entry, index) => {
    const routine = normalizeScheduleRoutine(entry, index);
    let id = routine.id;
    const baseId = id;
    let suffix = 2;
    while (seen.has(id.toLocaleLowerCase())) {
      id = `${baseId}-${suffix}`;
      suffix += 1;
    }
    seen.add(id.toLocaleLowerCase());
    routines.push({ ...routine, id });
  });
  return routines;
}

