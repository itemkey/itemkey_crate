export function normalizeLocale(value: unknown): Locale {
  return value === "en" ? "en" : DEFAULT_LOCALE;
}

export function isLocale(value: unknown): value is Locale {
  return SUPPORTED_LOCALES.includes(value as Locale);
}

export function resolveLocalePreference({
  accountLocale,
  cookieLocale,
}: {
  accountLocale?: unknown;
  cookieLocale?: unknown;
}): Locale {
  if (isLocale(accountLocale)) {
    return accountLocale;
  }
  return normalizeLocale(cookieLocale);
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values: TranslationValues = {}
): string {
  const template = (locale === "en" ? enMessages : ruMessages)[key] ?? ruMessages[key];
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => {
    const replacement = values[name];
    return replacement === undefined ? match : String(replacement);
  });
}

export function formatCount(
  locale: Locale,
  count: number,
  forms: { one: string; few?: string; many?: string; other: string }
): string {
  const category = new Intl.PluralRules(locale).select(count);
  const form =
    category === "one"
      ? forms.one
      : category === "few"
        ? forms.few ?? forms.other
        : category === "many"
          ? forms.many ?? forms.other
          : forms.other;
  return `${new Intl.NumberFormat(locale).format(count)} ${form}`;
}
